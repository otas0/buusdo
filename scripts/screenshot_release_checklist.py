#!/usr/bin/env python3
"""Freeze visual checklist images for release notes (main + About + tray mark)."""

from __future__ import annotations

import os
import sys
from pathlib import Path
from unittest.mock import patch

os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")

from PySide6.QtCore import Qt
from PySide6.QtGui import QPainter, QPixmap
from PySide6.QtWidgets import QApplication, QDialog

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from buusdo.core.backend import (  # noqa: E402
    EnhancementBackend,
    EnhancementTarget,
    InstallResult,
)
from buusdo.ui.about_dialog import show_about_dialog  # noqa: E402
from buusdo.ui.main_window import MainWindow  # noqa: E402
from buusdo.ui.theme import apply_product_theme  # noqa: E402
from buusdo.ui.tray_icon import app_icon, tray_icon  # noqa: E402

OUT_DIR = ROOT / "docs" / "fixtures" / "release_visual_checklist"


class _Stub(EnhancementBackend):
    def platform_id(self) -> str:
        return "macos"

    def discover_games(self, *, should_cancel=None, progress=None):
        return []

    def list_capabilities(self, target: EnhancementTarget):
        return []

    def install(self, target, options=None):
        return InstallResult(True, "ok")

    def uninstall(self, target):
        return InstallResult(True, "ok")

    def status(self, target):
        return {}


def _pump(app: QApplication, n: int = 30) -> None:
    for _ in range(n):
        app.processEvents()


def main() -> int:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    app = QApplication.instance() or QApplication([])
    apply_product_theme(app)

    with patch("buusdo.ui.main_window.needs_wizard", return_value=False):
        with patch.object(MainWindow, "_setup_tray", lambda self: None):
            win = MainWindow(backend=_Stub())
    win.resize(980, 720)
    win.show()
    _pump(app)
    main_path = OUT_DIR / "main_window.png"
    if not win.grab().save(str(main_path)):
        print(f"FAIL: {main_path}", file=sys.stderr)
        return 1

    # About is a modal helper; patch exec to keep it non-blocking under offscreen.
    about_path = OUT_DIR / "about_dialog.png"
    with patch.object(QDialog, "exec", lambda self: QDialog.DialogCode.Accepted):
        show_about_dialog(win)
        _pump(app)
        about = None
        for w in app.topLevelWidgets():
            if isinstance(w, QDialog) and w.objectName() == "instrumentDialog":
                about = w
                break
        if about is None:
            print("FAIL: About dialog not found", file=sys.stderr)
            return 1
        about.show()
        _pump(app)
        if not about.grab().save(str(about_path)):
            print(f"FAIL: {about_path}", file=sys.stderr)
            return 1
        about.close()

    row = QPixmap(420, 140)
    row.fill(Qt.GlobalColor.white)
    painter = QPainter(row)
    x = 16
    for side in (16, 32, 64, 128):
        pix = tray_icon().pixmap(side, side)
        painter.drawPixmap(x, (140 - side) // 2, pix)
        x += side + 24
    painter.end()
    icon_path = OUT_DIR / "tray_icon_sizes.png"
    if not row.save(str(icon_path)):
        print(f"FAIL: {icon_path}", file=sys.stderr)
        return 1

    assert not app_icon().isNull()
    assert not tray_icon().isNull()

    win.close()
    _pump(app)
    readme = OUT_DIR / "README.md"
    readme.write_text(
        "# Release visual checklist (frozen screenshots)\n\n"
        "Generated by `scripts/screenshot_release_checklist.py`.\n\n"
        "- `main_window.png` — primary UI\n"
        "- `about_dialog.png` — About with logo\n"
        "- `tray_icon_sizes.png` — 16/32/64(/128) tray mark\n\n"
        "Attach or link these in the next release notes after a visual smoke.\n",
        encoding="utf-8",
    )
    print(f"wrote {OUT_DIR}")
    for p in (main_path, about_path, icon_path, readme):
        print(f"  {p.name} ({p.stat().st_size} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
