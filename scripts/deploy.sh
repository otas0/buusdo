#!/usr/bin/env bash
# pyside6-deploy packaging skeleton for Windows / Linux / macOS artifacts.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

if ! command -v pyside6-deploy >/dev/null 2>&1; then
  echo "Install UI extra first: pip install -e '.[ui]'" >&2
  echo "Then ensure pyside6-deploy is on PATH." >&2
  exit 1
fi

ENTRY="${ROOT}/buusdo/app.py"
OUT="${ROOT}/dist"
mkdir -p "${OUT}"

# Nuitka-backed deploy; outputs vary by host (.exe / .bin / .app).
pyside6-deploy "${ENTRY}" -f -c "${ROOT}/scripts/pyside6-deploy.spec.json" || {
  echo "pyside6-deploy failed; falling back to module reminder." >&2
  echo "Manual: pyside6-deploy buusdo/app.py" >&2
  exit 1
}

echo "Artifacts under ${OUT} (host-dependent)."

_hash_file() {
  local f="$1"
  if command -v shasum >/dev/null 2>&1; then
    shasum -a 256 "${f}" | awk '{print $1}'
  elif command -v sha256sum >/dev/null 2>&1; then
    sha256sum "${f}" | awk '{print $1}'
  else
    echo "NOHASH"
  fi
}

# Always emit an UNSIGNED inventory with per-file sha256 for codesign before/after diff.
# .app bundles are always expanded. Set BUUSDO_UNSIGNED_RECURSIVE=1 to hash other dirs too
# (capped by BUUSDO_UNSIGNED_MAX_FILES, default 500).
UNSIGNED_RECURSIVE="${BUUSDO_UNSIGNED_RECURSIVE:-0}"
UNSIGNED_MAX_FILES="${BUUSDO_UNSIGNED_MAX_FILES:-500}"
{
  echo "# buusdo unsigned inventory — generated by scripts/deploy.sh"
  echo "# format: sha256  path"
  file_count=0
  while IFS= read -r p; do
    [[ -z "${p}" ]] && continue
    if [[ -d "${p}" && "${p}" == *.app ]]; then
      echo "# bundle ${p}"
      while IFS= read -r inner; do
        [[ -z "${inner}" ]] && continue
        echo "$(_hash_file "${inner}")  ${inner}"
        file_count=$((file_count + 1))
      done < <(find "${p}" -type f 2>/dev/null | sort || true)
    elif [[ -d "${p}" ]]; then
      if [[ "${UNSIGNED_RECURSIVE}" == "1" ]]; then
        echo "# dir-recursive ${p}"
        while IFS= read -r inner; do
          [[ -z "${inner}" ]] && continue
          if [[ "${file_count}" -ge "${UNSIGNED_MAX_FILES}" ]]; then
            echo "# truncated at ${UNSIGNED_MAX_FILES} files"
            break
          fi
          echo "$(_hash_file "${inner}")  ${inner}"
          file_count=$((file_count + 1))
        done < <(find "${p}" -type f 2>/dev/null | sort || true)
      else
        echo "DIR  ${p}"
      fi
    elif [[ -f "${p}" ]]; then
      echo "$(_hash_file "${p}")  ${p}"
      file_count=$((file_count + 1))
    fi
  done < <(find "${OUT}" -maxdepth 4 \( -type f -o -type d -name '*.app' -o -type d \) 2>/dev/null | sort || true)
} > "${OUT}/UNSIGNED.txt"

# Optional local codesign (scripts/codesign.env must exist; never committed).
if [[ "${BUUSDO_CODESIGN:-}" == "1" ]] || [[ -f "${ROOT}/scripts/codesign.env" ]]; then
  HOOK="${ROOT}/scripts/codesign_hooks.sh"
  if [[ -x "${HOOK}" ]]; then
    signed_any=0
    failed_paths=()
    unsigned_candidates=()
    while IFS= read -r art; do
      [[ -z "${art}" ]] && continue
      unsigned_candidates+=("${art}")
      echo "codesign: signing ${art}"
      if ! "${HOOK}" "${art}"; then
        echo "codesign: hook failed for ${art}" >&2
        failed_paths+=("${art}")
        if [[ "${BUUSDO_CODESIGN_STRICT:-}" != "1" ]]; then
          echo "codesign: continuing (set BUUSDO_CODESIGN_STRICT=1 to fail the build)" >&2
        fi
      else
        signed_any=1
        # Drop signed artifact from UNSIGNED inventory.
        if [[ -f "${OUT}/UNSIGNED.txt" ]]; then
          grep -vF "${art}" "${OUT}/UNSIGNED.txt" > "${OUT}/UNSIGNED.txt.tmp" || true
          mv "${OUT}/UNSIGNED.txt.tmp" "${OUT}/UNSIGNED.txt"
        fi
      fi
    done < <(find "${OUT}" -maxdepth 3 \( -name 'buusdo' -o -name 'buusdo.exe' -o -name 'buusdo.app' \) 2>/dev/null | head -5)
    if [[ ${#failed_paths[@]} -gt 0 ]]; then
      {
        echo "# sign failures"
        printf '%s\n' "${failed_paths[@]}"
      } >> "${OUT}/UNSIGNED.txt"
    fi
    if [[ "${signed_any}" -eq 0 && ${#unsigned_candidates[@]} -eq 0 ]]; then
      echo "codesign: no buusdo artifact found under ${OUT}; skip."
      if [[ "${BUUSDO_CODESIGN_STRICT:-}" == "1" ]]; then
        echo "codesign: strict mode — see ${OUT}/UNSIGNED.txt" >&2
        cat "${OUT}/UNSIGNED.txt" >&2 || true
        exit 1
      fi
    fi
    if [[ ${#failed_paths[@]} -gt 0 && "${BUUSDO_CODESIGN_STRICT:-}" == "1" ]]; then
      echo "codesign: strict mode — failed to sign (listed in UNSIGNED.txt):" >&2
      printf '  %s\n' "${failed_paths[@]}" >&2
      exit 1
    fi
  fi
fi
